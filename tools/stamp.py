"""Build-free cache busting. Rewrites the <!--stamp--> block in index.html (import map + asset URLs with ?v=<content hash>)
and regenerates sw.js (offline cache keyed by the same version). Run after changing any asset:  python3 tools/stamp.py
--check exits 1 if index.html/sw.js are out of date (used by CI)."""
import hashlib, pathlib, re, sys, json
R = pathlib.Path(__file__).resolve().parent.parent
def h(p): return hashlib.sha256((R / p).read_bytes()).hexdigest()[:10]
js = sorted(str(p.relative_to(R)) for p in (R / 'js').rglob('*.js'))
vend = {'three': 'vendor/three.custom.min.js', 'three/addons/utils/BufferGeometryUtils.js': 'vendor/three.custom.min.js', 'cannon-es': 'vendor/cannon.custom.min.js', 'peerjs': 'vendor/peerjs.mjs', 'supabase': 'vendor/supabase.mjs'}  # custom bundles: tools/bundle.py
imports = {k: f'./{v}?v={h(v)}' for k, v in vend.items()}
imports.update({f'./{p}': f'./{p}?v={h(p)}' for p in js if p != 'js/main.js'})
font = f'fonts/jua.woff2?v={h("fonts/jua.woff2")}'
main = f'js/main.js?v={h("js/main.js")}'
css = f'style.css?v={h("style.css")}'
static = ['icons/icon-192.png', 'icons/icon-512.png', 'icons/apple-touch-icon.png', 'icons/favicon.svg', 'manifest.json']
ver = hashlib.sha256(json.dumps([imports, font, main, css] + [h(p) for p in static if (R / p).exists()]).encode()).hexdigest()[:10]
block = f"""<!--stamp:begin (generated by tools/stamp.py — do not edit by hand)-->
<link rel="preload" href="{font}" as="font" type="font/woff2" crossorigin>
<style>@font-face{{font-family:Jua;src:url({font}) format('woff2');font-display:swap}}</style>
<link rel="stylesheet" href="{css}">
<script>window.__V='{ver}';</script>
<script type="importmap">{json.dumps({'imports': imports}, indent=0)}</script>
<script type="module" src="{main}"></script>
<!--stamp:end-->"""
idx = (R / 'index.html').read_text(encoding='utf-8')
new = re.sub(r'<!--stamp:begin.*?<!--stamp:end-->', lambda m: block, idx, flags=re.S)
assets = ['./', './index.html', css, main, font] + list(dict.fromkeys(imports.values())) + static
sw = (R / 'tools' / 'sw.template.js').read_text(encoding='utf-8').replace('__VERSION__', ver).replace('__ASSETS__', json.dumps(assets))
if '--check' in sys.argv:
    cur_sw = (R / 'sw.js').read_text(encoding='utf-8') if (R / 'sw.js').exists() else ''
    ok = new == idx and cur_sw == sw; print('stamp up to date' if ok else 'STAMP OUT OF DATE: run python3 tools/stamp.py'); sys.exit(0 if ok else 1)
(R / 'index.html').write_text(new, encoding='utf-8'); (R / 'sw.js').write_text(sw, encoding='utf-8'); print('stamped', ver)
